static void Local_Append_CRC8(uint8_t *pchMessage, uint32_t dwLength) 
{
    uint8_t ucCRC8 = CRC8_INIT;
    uint8_t ucIndex;
    uint32_t len = dwLength - 1;
    const uint8_t *ptr = pchMessage;
    while (len--) {
        ucIndex = ucCRC8 ^ (*ptr++);
        ucCRC8 = CRC8_TAB[ucIndex];
    }
    pchMessage[dwLength - 1] = ucCRC8;
}

