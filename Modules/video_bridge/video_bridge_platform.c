// 分配对齐的发送缓存
__attribute__((aligned(32))) uint8_t vtm_tx_buf[320];


bool bridge_platform_send_custom_0310(const uint8_t* data, uint16_t size) 
{
    // 如果视觉给的包超过 300，超出物理极限，直接扔掉
    if(size > 300) return false;

	
    // 静态包序号，每次发送自增（破解大疆图传的反重放拦截机制）
    static uint8_t seq_num = 0;

    //大疆图传 0x0310 强制要求有效载荷必须是 300！少 1 个字节图传都拒收！
    uint16_t fixed_payload_len = 300;           
    uint16_t total_size = fixed_payload_len + 9; // 整包总长固定为 309

    // --- 1. 组装官方帧头 (5字节) ---
    vtm_tx_buf[0] = 0xA5;         
    vtm_tx_buf[1] = fixed_payload_len & 0xFF;        // 填入 0x2C (即300)
    vtm_tx_buf[2] = (fixed_payload_len >> 8) & 0xFF; // 填入 0x01
    vtm_tx_buf[3] = seq_num++;                       // 包序号自增
    Local_Append_CRC8(vtm_tx_buf, 5); 

    // --- 2. 组装命令码 CMD_ID (0x0310，小端存放) ---
    vtm_tx_buf[5] = 0x10; 
    vtm_tx_buf[6] = 0x03; 

    // --- 3. 拷贝数据与补零填充 (Padding) ---
    // 先把 300 字节的有效载荷区全部清零 (填充尾部空间)
    memset(&vtm_tx_buf[7], 0, fixed_payload_len); 
    // 再把视觉发来的实际有效数据，原样覆盖到前部
    memcpy(&vtm_tx_buf[7], data, size);

    // --- 4. 组装整包 CRC16
    Local_Append_CRC16(vtm_tx_buf, total_size);

    // --- 5. 刷新 L1 Cache ---
    SCB_CleanDCache_by_Addr((uint32_t *)vtm_tx_buf, total_size);

    //改用 DMA 异步发送 ---
    if(HAL_UART_Transmit_DMA(&VTM_UART_HANDLE, vtm_tx_buf, total_size) == HAL_OK)
		{
        return true; 
    }

    
    return false; // 串口堵塞或发送失败
}



